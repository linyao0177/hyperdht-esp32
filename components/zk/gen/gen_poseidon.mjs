// circomlib Poseidon constants for t = 6 (5 inputs) -> poseidon_t6.h, plus
// reference hashes from circomlibjs for the tests
//
// usage: node gen_poseidon.mjs <circomlibjs dir> > poseidon_t6.h
import fs from 'fs';
import path from 'path';

const dir = process.argv[2];
const { C, M } = JSON.parse(fs.readFileSync(path.join(dir, 'src/poseidon_constants.json')));
const { buildPoseidon } = await import(path.join(dir, 'main.js'));
const poseidon = await buildPoseidon();
const F = poseidon.F;

const bytes = (x) => BigInt(x).toString(16).padStart(64, '0').match(/../g).map((b) => '0x' + b).join(',');
const T = 6;
const c = C[T - 2], m = M[T - 2];
console.log('// generated by gen_poseidon.mjs from circomlibjs poseidon_constants.json (t = 6)');
console.log(`#define POSEIDON_T6_ROUNDS ${c.length / T}`);
console.log(`static const uint8_t poseidon_t6_c[${c.length}][32] = {`);
for (const x of c) console.log(`  {${bytes(x)}},`);
console.log('};');
console.log(`static const uint8_t poseidon_t6_m[${T}][${T}][32] = {`);
for (const row of m) console.log('  {' + row.map((x) => `{${bytes(x)}}`).join(',') + '},');
console.log('};');

// reference: event (seq, t_ms, ev_id, conf_permille, box_packed)
const vectors = [
  [1n, 2n, 3n, 4n, 5n],
  [24n, 1793706235902n, 1n, 910n, 120n | (80n << 16n) | (64n << 32n) | (128n << 48n)],
  [0n, 0n, 0n, 0n, 0n],
  [(1n << 64n) - 1n, (1n << 64n) - 1n, 1n, 1000n, (1n << 64n) - 1n],
];
console.log(`static const struct { uint64_t in[5]; uint8_t out[32]; } poseidon_t6_vectors[${vectors.length}] = {`);
for (const v of vectors) {
  const h = F.toObject(poseidon(v));
  console.log(`  {{${v.map((x) => '0x' + x.toString(16) + 'ull').join(',')}}, {${bytes(h)}}},`);
}
console.log('};');
