"""snarkjs verification_key.json -> a C array in g16_vk_load's encoding

usage: python3 vk_header.py <verification_key.json> <array name> > out.h
"""
import json
import sys


def fe(s):
    return int(s).to_bytes(32, 'big')


def g1(p):
    assert p[2] == '1'
    return fe(p[0]) + fe(p[1])


def g2(p):  # snarkjs: [[x0, x1], [y0, y1], ...], x0 the real part; ours: imaginary first
    assert p[2] == ['1', '0']
    return fe(p[0][1]) + fe(p[0][0]) + fe(p[1][1]) + fe(p[1][0])


def vk_bytes(vk):
    assert vk['protocol'] == 'groth16' and vk['curve'] == 'bn128'
    assert len(vk['IC']) == vk['nPublic'] + 1
    b = g1(vk['vk_alpha_1']) + g2(vk['vk_beta_2']) + g2(vk['vk_gamma_2']) + g2(vk['vk_delta_2'])
    return b + b''.join(g1(p) for p in vk['IC'])


def carray(name, b):
    rows = [','.join(f'0x{x:02x}' for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return f'static const uint8_t {name}[{len(b)}] = {{\n  ' + ',\n  '.join(rows) + '\n};'


if __name__ == '__main__':
    print(f'// generated by components/zk/gen/vk_header.py from {sys.argv[1].split("/")[-1]}')
    print(carray(sys.argv[2], vk_bytes(json.load(open(sys.argv[1])))))
