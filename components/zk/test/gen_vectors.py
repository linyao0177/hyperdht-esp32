"""Test cases for zk_event from camera messages -> vectors.h

usage: python3 gen_vectors.py <verification_key.json> <events.jsonl> <root.hex> > vectors.h

events.jsonl holds messages as a camera sent them, each with a valid proof.
Each goes in as it is (valid), and the first also changed in every field
(the proof no longer fits) and broken in ways the parser must refuse.
"""
import json
import os
import sys
from decimal import Decimal

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'gen'))
from vk_header import carray, vk_bytes  # noqa: E402


def c_str(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"')
    return '"' + s.replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t') + '"'


def sub(text, a, b):
    assert a in text, a
    return text.replace(a, b, 1)


def dump(v):  # compact JSON, with Decimal numbers written as they are
    if isinstance(v, Decimal):
        return str(v)
    if isinstance(v, dict):
        return '{' + ','.join(json.dumps(k) + ':' + dump(x) for k, x in v.items()) + '}'
    if isinstance(v, list):
        return '[' + ','.join(dump(x) for x in v) + ']'
    return json.dumps(v)


vk = json.load(open(sys.argv[1]))
lines = [line.strip() for line in open(sys.argv[2]) if line.strip()]
root = bytes.fromhex(open(sys.argv[3]).read().strip())

# (name, json text, expected parse result, expected verify result, use another root)
cases = []
for i, line in enumerate(lines):
    cases.append((f'camera event {i}', line, 0, 1, 0))

ev = json.loads(lines[0], parse_float=Decimal)
changed = [
    ('seq + 1', {'seq': ev['seq'] + 1}),
    ('t + 1 ms', {'t': ev['t'] + 1}),
    ('ev -> motion', {'ev': 'motion'}),
    ('conf + 0.001', {'conf': ev['conf'] + Decimal('0.001')}),
    ('box h + 1', {'box': ev['box'][:3] + [ev['box'][3] + 1]}),
]
for name, change in changed:
    cases.append((name, dump({**ev, **change}), 0, 0, 0))
cases.append(('another root', lines[0], 0, 0, 1))

# the same event written differently: still valid
z = ev['zk']
rest = {k: v for k, v in ev.items() if k != 'zk'}
cases.append(('keys reordered', dump({'zk': z, **rest}), 0, 1, 0))
cases.append(('unknown keys skipped', dump({'v': 2, 'meta': {'a': [1, 'x', None, True]}, **ev, 'note': 'a,b}'}), 0, 1, 0))
cases.append(('spaces', '\n { ' + lines[0][1:-1].replace(',', ' ,\t').replace(':', ' : ') + ' }\r\n', 0, 1, 0))
cases.append(('conf trailing zero', sub(lines[0], f'"conf":{ev["conf"]}', f'"conf":{ev["conf"]}0'), 0, 1, 0))

# not an event
cases.append(('no zk key', dump(rest), 1, 0, 0))
cases.append(('plain text', 'hello', 1, 0, 0))

# malformed
bad = [
    ('conf 4 decimals', sub(lines[0], f'"conf":{ev["conf"]}', f'"conf":{ev["conf"]}1')),
    ('conf above 1', dump({**ev, 'conf': Decimal('1.001')})),
    ('conf exponent', sub(lines[0], f'"conf":{ev["conf"]}', '"conf":8.72e-1')),
    ('conf as string', dump({**ev, 'conf': str(ev['conf'])})),
    ('seq negative', dump({**ev, 'seq': -1})),
    ('seq fraction', dump({**ev, 'seq': Decimal('1.5')})),
    ('seq leading zero', sub(lines[0], f'"seq":{ev["seq"]},', f'"seq":0{ev["seq"]},')),
    ('seq over 64 bits', dump({**ev, 'seq': 2 ** 64})),
    ('box over 16 bits', dump({**ev, 'box': [65536, 0, 0, 0]})),
    ('box 3 numbers', dump({**ev, 'box': ev['box'][:3]})),
    ('unknown ev', dump({**ev, 'ev': 'car'})),
    ('zk short', dump({**ev, 'zk': z[:-2]})),
    ('zk not hex', dump({**ev, 'zk': 'g' + z[1:]})),
    ('missing t', dump({k: v for k, v in ev.items() if k != 't'})),
    ('seq twice', sub(lines[0], '{', '{"seq":1,')),
    ('trailing text', lines[0] + 'x'),
    ('two objects', lines[0] + lines[0]),
    ('truncated', lines[0][:-1]),
    ('array', '[' + lines[0] + ']'),
    ('escape in ev', sub(lines[0], '"person"', '"pers\\u006fn"')),
]
for name, text in bad:
    cases.append((name, text, -1, 0, 0))

print('// generated by gen_vectors.py')
print(carray('vk_bin', vk_bytes(vk)))
print(carray('root', root))
print('static const struct { const char *name; const char *json; int parse; int verify; int other_root; } cases[] = {')
for name, text, p, v, o in cases:
    print(f'  {{{c_str(name)}, {c_str(text)}, {p}, {v}, {o}}},')
print('};')
