void
hdht_hash (uint8_t out[32], const void *data, size_t len) {
  crypto_generichash(out, 32, data, len, NULL, 0);
}

void
hdht_node_id (uint8_t out[32], const hdht_addr_t *addr) {
  uint8_t b[6];
  memcpy(b, addr->ip, 4);
  b[4] = (uint8_t) addr->port;
  b[5] = (uint8_t) (addr->port >> 8);
  hdht_hash(out, b, sizeof(b));
}

void
hdht_holepunch_secret (uint8_t out[32], const uint8_t handshake_hash[64]) {
  crypto_generichash(out, 32, HDHT_NS_PEER_HOLEPUNCH, 32, handshake_hash, 64);
}

void
hdht_stream_id (uint8_t out[32], const uint8_t handshake_hash[64], bool initiator) {
  crypto_generichash(out, 32, initiator ? HDHT_SS_NS_INITIATOR : HDHT_SS_NS_RESPONDER, 32, handshake_hash, 64);
}

int
hdht_ip_to_string (const uint8_t ip[4], char *out) {
  return snprintf(out, 16, "%u.%u.%u.%u", ip[0], ip[1], ip[2], ip[3]);
}

void
hdht_addr_token (uint8_t out[32], const hdht_addr_t *addr, const uint8_t secret[32]) {
  char host[16];
  int n = hdht_ip_to_string(addr->ip, host);
  crypto_generichash(out, 32, (const uint8_t *) host, (size_t) n, secret, 32);
}
