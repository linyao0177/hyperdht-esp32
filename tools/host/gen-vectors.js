// Generates byte-exact test vectors from the JS reference implementation for
// the C port (components/hdht/test/vectors.h).
//
//   node gen-vectors.js > ../../components/hdht/test/vectors.h

const NoiseHandshake = require('noise-handshake')
const curve = require('noise-curve-ed')
const sodium = require('sodium-universal')
const c = require('compact-encoding')
const b4a = require('b4a')
const NoiseSecretStream = require('@hyperswarm/secret-stream')
const m = require('hyperdht/lib/messages')
const { NS } = require('hyperdht/lib/constants')
const Persistent = require('hyperdht/lib/persistent')

const lines = ['// Generated by tools/host/gen-vectors.js from the JS reference. Do not edit.', '']

function keyPair(byte) {
  const publicKey = b4a.alloc(32)
  const secretKey = b4a.alloc(64)
  sodium.crypto_sign_seed_keypair(publicKey, secretKey, b4a.alloc(32, byte))
  return { publicKey, secretKey }
}

function emit(name, buf) {
  const bytes = []
  for (const b of buf) bytes.push('0x' + b.toString(16).padStart(2, '0'))
  const rows = []
  for (let i = 0; i < bytes.length; i += 12) rows.push('  ' + bytes.slice(i, i + 12).join(', '))
  lines.push(`static const uint8_t ${name}[${buf.byteLength}] = {`)
  lines.push(rows.join(',\n'))
  lines.push('};')
  lines.push('')
}

// Noise IK with fixed static and ephemeral keys
const initiator = keyPair(0x01)
const responder = keyPair(0x02)
const initiatorE = keyPair(0x03)
const responderE = keyPair(0x04)

const fixedCurve = (e) => ({ ...curve, generateKeyPair: () => e })

const a = new NoiseHandshake('IK', true, initiator, { curve: fixedCurve(initiatorE) })
const b = new NoiseHandshake('IK', false, responder, { curve: fixedCurve(responderE) })
a.initialise(NS.PEER_HANDSHAKE, responder.publicKey)
b.initialise(NS.PEER_HANDSHAKE)

const payload1 = c.encode(m.noisePayload, {
  error: 0,
  firewall: 0,
  holepunch: null,
  addresses4: [{ host: '192.168.31.7', port: 49737 }],
  addresses6: [],
  udx: { reusableSocket: false, id: 0x12345678, seq: 0 },
  secretStream: {},
  relayThrough: null
})

const payload2 = c.encode(m.noisePayload, {
  error: 0,
  firewall: 2,
  holepunch: {
    id: 3,
    relays: [{ relayAddress: { host: '1.2.3.4', port: 49737 }, peerAddress: { host: '5.6.7.8', port: 1000 } }]
  },
  addresses4: [{ host: '10.0.0.2', port: 5000 }],
  addresses6: [],
  udx: { reusableSocket: false, id: 0xdeadbeef, seq: 0 },
  secretStream: {},
  relayThrough: null,
  relayAddresses: [{ host: '1.2.3.4', port: 49737 }]
})

const msg1 = a.send(payload1)
b.recv(b4a.from(msg1)) // recv keeps a view of the buffer and zeroes it in final()
const msg2 = b.send(payload2)
a.recv(b4a.from(msg2))

emit('NOISE_I_SEED_PK', initiator.publicKey)
emit('NOISE_R_PK', responder.publicKey)
emit('NOISE_PAYLOAD1', payload1)
emit('NOISE_PAYLOAD2', payload2)
emit('NOISE_MSG1', msg1)
emit('NOISE_MSG2', msg2)
emit('NOISE_HASH', a.hash)
emit('NOISE_I_TX', a.tx)
emit('NOISE_I_RX', a.rx)

const holepunchSecret = b4a.alloc(32)
sodium.crypto_generichash(holepunchSecret, NS.PEER_HOLEPUNCH, a.hash)
emit('NOISE_HOLEPUNCH_SECRET', holepunchSecret)
emit('SS_ID_INITIATOR', NoiseSecretStream.id(a.hash, true))
emit('SS_ID_RESPONDER', NoiseSecretStream.id(a.hash, false))

// Messages
emit('MSG_HANDSHAKE', c.encode(m.handshake, { mode: 2, noise: b4a.from([1, 2, 3]), peerAddress: { host: '9.8.7.6', port: 65535 }, relayAddress: null }))
emit('MSG_HOLEPUNCH', c.encode(m.holepunch, { mode: 0, id: 300, payload: b4a.alloc(70, 0xaa), peerAddress: { host: '9.8.7.6', port: 1 } }))
emit('MSG_HOLEPUNCH_PAYLOAD', c.encode(m.holepunchPayload, {
  error: 0,
  firewall: 2,
  round: 1,
  connected: false,
  punching: true,
  addresses: [{ host: '5.6.7.8', port: 1000 }],
  remoteAddress: null,
  token: b4a.alloc(32, 0x07),
  remoteToken: b4a.alloc(32, 0x08)
}))

// Announce signature
const target = b4a.alloc(32)
sodium.crypto_generichash(target, responder.publicKey)
const nodeId = b4a.alloc(32, 0x21)
const token = b4a.alloc(32, 0x22)
const ann = { peer: { publicKey: responder.publicKey, relayAddresses: [] }, refresh: null, signature: null }
ann.signature = Persistent.signAnnounce(target, token, nodeId, ann, responder)
emit('ANN_TARGET', target)
emit('ANN_NODE_ID', nodeId)
emit('ANN_TOKEN', token)
emit('ANN_VALUE', c.encode(m.announce, ann))

process.stdout.write(lines.join('\n'))
