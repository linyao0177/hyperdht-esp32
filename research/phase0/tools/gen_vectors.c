// Generates main/sodium_vectors.h from the host's libsodium so the device
// can check that its libsodium build produces byte-identical results for
// every primitive HyperDHT uses.
//
//   cc tools/gen_vectors.c -I/opt/homebrew/include -L/opt/homebrew/lib -lsodium -o /tmp/gen_vectors
//   /tmp/gen_vectors > main/sodium_vectors.h

#include <sodium.h>
#include <stdio.h>
#include <string.h>

static void
emit (const char *name, const unsigned char *buf, size_t len) {
  printf("static const unsigned char %s[%zu] = {", name, len);
  for (size_t i = 0; i < len; i++) {
    printf("%s0x%02x", i % 12 == 0 ? "\n  " : " ", buf[i]);
    if (i + 1 < len) printf(",");
  }
  printf("\n};\n\n");
}

// Same derivation as noise-curve-ed's dh(): sha512(seed), clamp, noclamp mult.
static int
ed_dh (unsigned char out[32], const unsigned char seed[32], const unsigned char pk[32]) {
  unsigned char sk[64];
  crypto_hash_sha512(sk, seed, 32);
  sk[0] &= 248;
  sk[31] &= 127;
  sk[31] |= 64;
  return crypto_scalarmult_ed25519_noclamp(out, sk, pk);
}

int
main (void) {
  if (sodium_init() < 0) return 1;

  unsigned char seed_a[32], seed_b[32], nonce12[12], nonce24[24];
  for (int i = 0; i < 32; i++) seed_a[i] = (unsigned char) (i + 1);
  for (int i = 0; i < 32; i++) seed_b[i] = (unsigned char) (i + 0x21);
  for (int i = 0; i < 12; i++) nonce12[i] = (unsigned char) i;
  for (int i = 0; i < 24; i++) nonce24[i] = (unsigned char) i;

  const unsigned char *msg = (const unsigned char *) "holepunch-esp32c3";
  size_t msg_len = strlen((const char *) msg);

  unsigned char pk_a[32], sk_a[64], pk_b[32], sk_b[64];
  crypto_sign_seed_keypair(pk_a, sk_a, seed_a);
  crypto_sign_seed_keypair(pk_b, sk_b, seed_b);

  unsigned char sig_a[64];
  crypto_sign_detached(sig_a, NULL, msg, msg_len, sk_a);

  unsigned char dh_ab[32];
  if (ed_dh(dh_ab, seed_a, pk_b) != 0) return 1;

  unsigned char b2b[32], b2b_keyed[32], sha512[64];
  crypto_generichash(b2b, 32, msg, msg_len, NULL, 0);
  crypto_generichash(b2b_keyed, 32, msg, msg_len, pk_a, 32);
  crypto_hash_sha512(sha512, msg, msg_len);

  unsigned char aead[64];
  unsigned long long aead_len;
  crypto_aead_chacha20poly1305_ietf_encrypt(aead, &aead_len, msg, msg_len, pk_a, 32, NULL, nonce12, seed_a);

  unsigned char xaead[64];
  unsigned long long xaead_len;
  crypto_aead_xchacha20poly1305_ietf_encrypt(xaead, &xaead_len, msg, msg_len, pk_a, 32, NULL, nonce24, seed_a);

  unsigned char box[64];
  crypto_secretbox_easy(box, msg, msg_len, nonce24, seed_b);

  printf("// Generated by tools/gen_vectors.c with host libsodium %s. Do not edit.\n\n", sodium_version_string());
  printf("#pragma once\n\n");
  printf("#define VEC_MSG \"holepunch-esp32c3\"\n\n");
  emit("vec_pk_a", pk_a, 32);
  emit("vec_pk_b", pk_b, 32);
  emit("vec_sig_a", sig_a, 64);
  emit("vec_dh_ab", dh_ab, 32);
  emit("vec_blake2b", b2b, 32);
  emit("vec_blake2b_keyed", b2b_keyed, 32);
  emit("vec_sha512", sha512, 64);
  emit("vec_chacha20poly1305_ietf", aead, (size_t) aead_len);
  emit("vec_xchacha20poly1305_ietf", xaead, (size_t) xaead_len);
  emit("vec_secretbox", box, msg_len + crypto_secretbox_MACBYTES);
  return 0;
}
